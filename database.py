import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool
from config import DATABASE_URL

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is missing. Set it in your .env file.")

pool = ConnectionPool(
    conninfo=DATABASE_URL,
    min_size=1,
    max_size=10,
    kwargs={"row_factory": dict_row},
    open=True,
)


def init_db():
    with pool.connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                conversation_key TEXT NOT NULL,
                role TEXT NOT NULL,
                content TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS user_settings (
                conversation_key TEXT PRIMARY KEY,
                model TEXT NOT NULL
            )
        """)
        conn.execute(
            "UPDATE user_settings SET model = %s WHERE model IN (%s, %s, %s)",
            ("gemini-3.1-flash-lite", "gemini-2.5-flash", "gemini-2.5-pro", "gemini-3.8-flash"),
        )
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_messages_conversation
            ON messages(conversation_key, id)
        """)


def get_history(conversation_key: str, limit: int = 20):
    with pool.connection() as conn:
        rows = conn.execute(
            """SELECT role, content FROM messages
               WHERE conversation_key = %s
               ORDER BY id DESC LIMIT %s""",
            (conversation_key, limit),
        ).fetchall()
    return [dict(row) for row in reversed(rows)]


def add_message(conversation_key: str, role: str, content: str):
    with pool.connection() as conn:
        conn.execute(
            "INSERT INTO messages (conversation_key, role, content) VALUES (%s, %s, %s)",
            (conversation_key, role, content),
        )


def clear_history(conversation_key: str):
    with pool.connection() as conn:
        conn.execute(
            "DELETE FROM messages WHERE conversation_key = %s",
            (conversation_key,),
        )


def get_model(conversation_key: str):
    with pool.connection() as conn:
        row = conn.execute(
            "SELECT model FROM user_settings WHERE conversation_key = %s",
            (conversation_key,),
        ).fetchone()
    return row["model"] if row else None


def set_model(conversation_key: str, model: str):
    with pool.connection() as conn:
        conn.execute(
            """INSERT INTO user_settings (conversation_key, model) VALUES (%s, %s)
               ON CONFLICT(conversation_key) DO UPDATE SET model = excluded.model""",
            (conversation_key, model),
        )
